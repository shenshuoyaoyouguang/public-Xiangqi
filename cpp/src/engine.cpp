constexpr std::size_t kMaxCommandHistory = 1024;

std::vector<std::string> split_words(std::string_view line) {
    std::istringstream stream{std::string(line)};
    std::vector<std::string> words;
    std::string word;
    while (stream >> word) words.push_back(std::move(word));
    return words;
}

template <typename Integer>
bool parse_integer(std::string_view text, Integer& value) {
    if (text.empty()) return false;
    const auto result = std::from_chars(text.data(), text.data() + text.size(), value);
    return result.ec == std::errc{} && result.ptr == text.data() + text.size();
}

#ifndef _WIN32
bool write_pipe(int descriptor, std::string_view data) {
    sigset_t pipe_signal{};
    if (sigemptyset(&pipe_signal) != 0 || sigaddset(&pipe_signal, SIGPIPE) != 0) return false;

    sigset_t old_mask{};
    if (pthread_sigmask(SIG_BLOCK, &pipe_signal, &old_mask) != 0) return false;

    const char* current = data.data();
    std::size_t remaining = data.size();
    int write_error = 0;
    while (remaining > 0) {
        const ssize_t written = ::write(descriptor, current, remaining);
        if (written > 0) {
            current += written;
            remaining -= static_cast<std::size_t>(written);
        } else if (written < 0 && errno == EINTR) {
            continue;
        } else {
            write_error = written < 0 ? errno : EIO;
            break;
        }
    }

    // A blocked SIGPIPE remains pending after write(2) reports EPIPE. Consume
    // the signal generated by this write before restoring the old mask.
    if (write_error == EPIPE) {
        const timespec timeout{0, 0};
        while (sigtimedwait(&pipe_signal, nullptr, &timeout) < 0 && errno == EINTR) {}
    }
    const bool restored = pthread_sigmask(SIG_SETMASK, &old_mask, nullptr) == 0;
    return write_error == 0 && restored;
}
#endif

